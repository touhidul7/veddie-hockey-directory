const assert=require('node:assert/strict');
const crypto=require('node:crypto');
process.env.NODE_ENV='test';
process.env.ADMIN_TOKEN=crypto.randomBytes(32).toString('hex');
process.env.RINKCIRCUIT_TEST_SCHEMA='rinkcircuit_test_'+crypto.randomBytes(8).toString('hex');
const {getDb,closeDb}=require('../server/db/database');
const {migrate}=require('../server/db/migrate');
const {previewAndStageBatch,getBatchReview,commitStagedBatch,reviewImportRow}=require('../server/services/importService');
const db=getDb();
let server;
async function run(){
  await migrate();
  const rows=[
    {League:'Fixture A',Area:'Toronto',Category:'Ice',Source:'https://example.com/a','Checked on':'2020-01-01',notes:'PRIVATE CONTACT'},
    {League:'Fixture B',Area:'Toronto',Category:'Ice',Source:'https://example.com/b'},
    {League:'Bad URL',Area:'Toronto',Category:'Ice',Source:'https://user:secret@example.com'},
  ];
  const preview=await previewAndStageBatch('fixture.csv','test',rows);
  assert.equal(preview.stagedRows[0].freshness,'stale');
  assert.equal(preview.stagedRows[0].plannedAction,'create_published');
  assert.equal(preview.stagedRows[2].selectable,false);
  assert.deepEqual(preview.stagedRows[2].sources,[]);
  assert.ok(!JSON.stringify(preview).includes('PRIVATE CONTACT'));
  assert.ok(!JSON.stringify(preview).includes('user:secret'));
  assert.equal((await db.get('SELECT count(*) AS count FROM rinkcircuit.league_programmes')).count,0);
  await commitStagedBatch(preview.batchId,[preview.stagedRows[0].id]);
  const saved=await getBatchReview(preview.batchId);
  assert.equal(saved.status,'partially_reviewed');assert.equal(saved.summary.approved,1);assert.equal(saved.summary.pending,2);
  const existing=await previewAndStageBatch('existing.csv','test',[{...rows[0],Category:'Ball'}]);
  assert.equal(existing.stagedRows[0].plannedAction,'preserve_existing');
  assert.equal(existing.stagedRows[0].fields.find(f=>f.field==='category').changed,true);
  await db.run("UPDATE rinkcircuit.league_programmes SET version=version+1, category='Manual value'");
  const updated=await getBatchReview(existing.batchId);
  assert.ok(updated.stagedRows[0].flags.includes('changed_since_staging'));
  assert.equal(updated.stagedRows[0].fields.find(f=>f.field==='category').current,'Manual value');
  await commitStagedBatch(existing.batchId,[existing.stagedRows[0].id]);
  assert.equal((await db.get('SELECT category FROM rinkcircuit.league_programmes')).category,'Manual value');
  const late=await previewAndStageBatch('late.csv','test',[{...rows[0],League:'Added later'}]);
  const now=new Date().toISOString();
  await db.run(`INSERT INTO rinkcircuit.league_programmes(id,name,slug,area,municipality,category,created_at,updated_at)
    VALUES ('manual','Added later','added-later','Toronto','Toronto','Ice',?,?)`,now,now);
  assert.equal((await getBatchReview(late.batchId)).stagedRows[0].plannedAction,'preserve_existing');
  assert.equal((await commitStagedBatch(late.batchId,[late.stagedRows[0].id])).createdCount,0);
  assert.equal((await db.get("SELECT count(*) AS count FROM rinkcircuit.league_programmes WHERE name='Added later'")).count,1);
  const original=await db.get('SELECT raw_data_json FROM rinkcircuit.import_rows WHERE id=?',preview.stagedRows[2].id);
  const correction={action:'correct',version:1,reason:'Replaced invalid source with an official page',name:'Bad URL',area:'Toronto',category:'Ice',source:'https://example.com/fixed'};
  const corrected=await reviewImportRow(preview.batchId,preview.stagedRows[2].id,correction,'reviewer');
  const correctedRow=corrected.stagedRows.find(r=>r.id===preview.stagedRows[2].id);
  assert.equal(correctedRow.reviewVersion,2);assert.equal(correctedRow.selectable,true);assert.equal(correctedRow.checkedAt,null);
  assert.equal((await db.get('SELECT raw_data_json FROM rinkcircuit.import_rows WHERE id=?',correctedRow.id)).raw_data_json,original.raw_data_json);
  await assert.rejects(commitStagedBatch(preview.batchId,[correctedRow.id],'reviewer',{[correctedRow.id]:1}),error=>error.status===409);
  const results=await Promise.allSettled([reviewImportRow(preview.batchId,correctedRow.id,{action:'reject',version:2,reason:'Not in current scope'},'reviewer'),reviewImportRow(preview.batchId,correctedRow.id,{action:'reject',version:2,reason:'Duplicate review'},'reviewer')]);
  assert.equal(results.filter(r=>r.status==='fulfilled').length,1);assert.equal(results.find(r=>r.status==='rejected').reason.status,409);
  assert.equal((await db.get('SELECT status FROM rinkcircuit.import_rows WHERE id=?',correctedRow.id)).status,'rejected');
  assert.equal((await commitStagedBatch(preview.batchId,[correctedRow.id])).createdCount,0);
  const applicant=await previewAndStageBatch('applicant.csv','test',[{League:'Applicant',Area:'Toronto',Category:'Applicant',Source:'https://example.com/applicant'}]);
  const resolved=await reviewImportRow(applicant.batchId,applicant.stagedRows[0].id,{...correction,name:'Renamed team',category:'Ice'},'reviewer');
  assert.equal(resolved.stagedRows[0].plannedAction,'create_draft');
  assert.equal((await db.get("SELECT count(*) AS count FROM rinkcircuit.audit_logs WHERE action IN ('import_correct','import_reject')")).count,3);
  const classification={action:'classify_programme',version:2,reason:'Official source identifies this adult league',evidenceReviewed:true,evidenceUrl:correction.source};
  const applicantId=applicant.stagedRows[0].id;
  await assert.rejects(reviewImportRow(applicant.batchId,applicantId,{...classification,evidenceReviewed:false},'reviewer'),e=>e.status===400);
  await assert.rejects(reviewImportRow(applicant.batchId,applicantId,{...classification,evidenceUrl:'https://example.com/unrelated'},'reviewer'),e=>e.status===400);
  await assert.rejects(reviewImportRow(applicant.batchId,applicantId,{...classification,evidenceUrl:'https://example.com/ice-allocation-entitlements.pdf'},'reviewer'),e=>e.status===400);
  const classified=await reviewImportRow(applicant.batchId,applicantId,classification,'reviewer');
  assert.ok(!classified.stagedRows[0].flags.includes('applicant_lead'));
  assert.ok(classified.stagedRows[0].flags.includes('publication_hold'));
  assert.equal(classified.stagedRows[0].plannedAction,'create_draft');
  await assert.rejects(reviewImportRow(applicant.batchId,applicantId,classification,'reviewer'),e=>e.status===409);
  await commitStagedBatch(applicant.batchId,[applicantId]);
  assert.equal((await db.get("SELECT publication_status FROM rinkcircuit.league_programmes WHERE name='Renamed team'")).publication_status,'draft');
  const held=await previewAndStageBatch('hold.csv','test',[{League:'Shared venue candidate',Area:'Toronto',Category:'Ice',Source:'https://example.com/venue'}]);
  const heldId=held.stagedRows[0].id;
  const onHold=await reviewImportRow(held.batchId,heldId,{action:'hold',version:1,reason:'Resolve overlapping programme and venue records'},'reviewer');
  assert.equal(onHold.stagedRows[0].plannedAction,'needs_review');assert.equal(onHold.stagedRows[0].selectable,false);
  assert.equal((await commitStagedBatch(held.batchId,[heldId],'reviewer',{[heldId]:2})).createdCount,0);
  const stillHeld=await reviewImportRow(held.batchId,heldId,{...correction,version:2,name:'Corrected venue'},'reviewer');
  assert.equal(stillHeld.stagedRows[0].selectable,false);
  assert.equal((await commitStagedBatch(held.batchId,[heldId])).createdCount,0);
  const release={action:'resolve_hold',version:3,evidenceReviewed:true,evidenceUrl:correction.source,reason:'Official evidence resolves the shared venue scope',programmeScope:'One adult league with separate winter divisions at two venues. Current availability remains unknown.'};
  await assert.rejects(reviewImportRow(held.batchId,heldId,{...release,evidenceReviewed:false},'reviewer'),e=>e.status===400);
  await assert.rejects(reviewImportRow(held.batchId,heldId,{...release,evidenceUrl:'https://example.com/unrelated'},'reviewer'),e=>e.status===400);
  await assert.rejects(reviewImportRow(held.batchId,heldId,{...release,programmeScope:'short'},'reviewer'),e=>e.status===400);
  const released=await reviewImportRow(held.batchId,heldId,release,'reviewer');
  assert.equal(released.stagedRows[0].plannedAction,'create_draft');
  assert.equal(released.stagedRows[0].editorialResolution.scope,release.programmeScope);
  await assert.rejects(reviewImportRow(held.batchId,heldId,release,'reviewer'),e=>e.status===409);
  const invalidated=await reviewImportRow(held.batchId,heldId,{...correction,version:4,name:'Different programme'},'reviewer');
  assert.equal(invalidated.stagedRows[0].plannedAction,'needs_review');assert.equal(invalidated.stagedRows[0].editorialResolution,null);
  assert.equal((await commitStagedBatch(held.batchId,[heldId])).createdCount,0);
  await reviewImportRow(held.batchId,heldId,{...release,version:5},'reviewer');
  await commitStagedBatch(held.batchId,[heldId]);
  assert.equal((await db.get("SELECT publication_status FROM rinkcircuit.league_programmes WHERE name='Different programme'")).publication_status,'draft');
  const classificationAudit=await db.get("SELECT details_json FROM rinkcircuit.audit_logs WHERE action='import_classify_programme' AND entity_id=?",applicantId);
  const auditDetails=JSON.parse(classificationAudit.details_json);
  assert.equal(auditDetails.evidence.url,classification.evidenceUrl);assert.ok(auditDetails.afterFlags.includes('publication_hold'));
  const app=require('../server/index');server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
  const base=`http://127.0.0.1:${server.address().port}`;
  const login=await fetch(base+'/api/admin/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({username:process.env.ADMIN_USER||'admin',password:process.env.ADMIN_TOKEN})});
  assert.equal(login.status,200);
  const headers={'Content-Type':'application/json',Cookie:login.headers.get('set-cookie').split(';')[0],'x-csrf-token':(await login.json()).csrfToken};
  const api=async(path,body)=>fetch(base+path,{method:'POST',headers,body:JSON.stringify(body)});
  assert.equal((await api('/api/admin/imports/preview',{csv:'League,Area\nA,B'})).status,400);
  const staged=await api('/api/admin/imports/preview',{csv:'League,Area,Category,Source\n"API, quoted",Toronto,Ice,https://example.com/api'});
  assert.equal(staged.status,200);const data=await staged.json();const apiRow=data.stagedRows[0];assert.equal(apiRow.candidateName,'API, quoted');
  assert.equal((await api(`/api/admin/imports/${data.batchId}/commit`,{approvedRowIds:[apiRow.id]})).status,400);
  const rejected=await api(`/api/admin/imports/${data.batchId}/rows/${apiRow.id}/review`,{action:'reject',version:apiRow.reviewVersion,reason:'Outside directory scope'});
  assert.equal(rejected.status,200);assert.equal((await rejected.json()).stagedRows[0].status,'rejected');
  console.log('Import CSV API, comparison, correction, rejection, stale-review, provenance and privacy checks passed.');
}
run().catch(error=>{console.error('Import review test failed:',error.code||error.message);process.exitCode=1;}).finally(async()=>{
  if(server)await new Promise(resolve=>server.close(resolve));
  try{await db.exec('DROP SCHEMA IF EXISTS rinkcircuit CASCADE');}finally{await closeDb();}
});
